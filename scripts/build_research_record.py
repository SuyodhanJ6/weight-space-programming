#!/usr/bin/env python3
"""Regenerate docs/wsp-research-record/{04_RESULTS_SUMMARY,05_ITERATION_LEDGER}.md and data/ snapshots.

Read-only with respect to experiments: it only reads their artifacts and writes into docs/wsp-research-record/.
Run from the repository root:  python scripts/build_research_record.py
"""

from __future__ import annotations

import json
import shutil
from pathlib import Path

OUT = Path("docs/wsp-research-record")
EXPERIMENTS = {
    "wsp-001": {"dir": Path("experiments"), "acc_key": "loo_acc", "acc_label": "LOO", "sizes": "12 / 4 / 4"},
    "wsp-002": {"dir": Path("experiments/wsp-002"), "acc_key": "cv_acc", "acc_label": "CV", "sizes": "1,000 / 600 / 2,000"},
    "wsp-003": {"dir": Path("experiments/wsp-003"), "acc_key": "cv_acc", "acc_label": "CV", "sizes": "8,000 / 3,000 / 6,000"},
    "wsp-004": {"dir": Path("experiments/wsp-004"), "acc_key": "cv_acc", "acc_label": "CV", "sizes": "8,000 / 3,000 / 3,884"},
    "wsp-005": {"dir": Path("experiments/wsp-005"), "acc_key": "cv_acc", "acc_label": "CV", "sizes": "12 / 4 / 4"},
    "wsp-006": {"dir": Path("experiments/wsp-006"), "acc_key": "loo_acc", "acc_label": "LOO(16)", "sizes": "12 / 4 / 4"},
}
SNAPSHOT_FILES = ["experiment_state.json", "experiment_history.json", "parameter_changes.json", "decision_log.md",
                  "controls.json", "final_test_results.json", "audit_report.json", "dataset_report.json"]


def load(path: Path, default=None):
    return json.loads(path.read_text()) if path.exists() else default


def pct(x: float | None) -> str:
    return "-" if x is None else f"{x * 100:.1f}%"


def snapshot_data() -> None:
    for name, cfg in EXPERIMENTS.items():
        dest = OUT / "data" / name
        dest.mkdir(parents=True, exist_ok=True)
        for fname in SNAPSHOT_FILES:
            src = cfg["dir"] / fname
            if src.exists():
                shutil.copyfile(src, dest / fname)
        wu = Path("reports") / ("" if name == "wsp-001" else name) / "WEIGHT_UPDATE_AUDIT.md"
        if wu.exists():
            shutil.copyfile(wu, dest / "WEIGHT_UPDATE_AUDIT.md")


def summary() -> str:
    lines = ["# 04 - Results summary (generated by scripts/build_research_record.py)", "",
             "All numbers are read from the experiment artifacts. 'Test' is the sealed split read exactly once per experiment.", ""]
    lines += ["## Headline table", "",
              "| Experiment | Split sizes (train/val/test) | Iterations | Accepted | Baseline val | Final val | Baseline test | Final test | Audit |",
              "|---|---|---|---|---|---|---|---|---|"]
    details = []
    for name, cfg in EXPERIMENTS.items():
        d = cfg["dir"]
        st, hist = load(d / "experiment_state.json", {}), load(d / "experiment_history.json", [])
        its = [h for h in hist if h.get("id") != "iter000"]
        acc = [h["id"] for h in its if h.get("decision") == "accepted"]
        tst, aud = load(d / "final_test_results.json"), load(d / "audit_report.json")
        b, f = st.get("baseline_metrics", {}), st.get("metrics", {})
        ti = pct(tst["initial"]["accuracy"]) if tst else "not yet run"
        tf = pct(tst["final"]["accuracy"]) if tst else "not yet run"
        lines.append(f"| {name} | {cfg['sizes']} | {len(its)} | {len(acc)} ({', '.join(acc) or 'none'}) | {pct(b.get('val_acc'))} | "
                     f"{pct(f.get('val_acc'))} | {ti} | {tf} | {'PASSED' if aud and aud.get('passed') else ('n/a' if not aud else 'FAILED')} |")
        details.append((name, cfg, st, its, tst, aud))
    lines += ["", "Note: WSP-001 'val' has 4 images and its test 4 images: its numbers are not statistically meaningful.", ""]
    for name, cfg, st, its, tst, aud in details:
        b, f = st.get("baseline_metrics", {}), st.get("metrics", {})
        lines += [f"## {name}", "",
                  f"* Status: **{st.get('status')}**; last completed: `{st.get('last_completed')}`; final checkpoint: `{st.get('accepted_checkpoint')}`",
                  f"* Architecture: {st.get('architecture')}",
                  f"* Baseline (iter000): train {pct(b.get('train_acc'))}, val {pct(b.get('val_acc'))}, {cfg['acc_label']} {pct(b.get(cfg['acc_key']))}",
                  f"* Final: train {pct(f.get('train_acc'))}, val {pct(f.get('val_acc'))}, {cfg['acc_label']} {pct(f.get(cfg['acc_key']))}"]
        if tst:
            for key in ("initial", "final", "reference"):
                if key in tst:
                    r = tst[key]
                    ci = r.get("accuracy_ci95")
                    lines.append(f"* Sealed test, **{key}** (`{r['checkpoint']}`): accuracy {pct(r['accuracy'])}"
                                 + (f" (95% CI {pct(ci[0])}-{pct(ci[1])})" if ci else "")
                                 + f", precision {r['precision']:.3f}, recall {r['recall']:.3f}, F1 {r['f1']:.3f}, confusion {r['confusion']}")
            for key in ("paired", "paired_vs_reference"):
                if key in tst:
                    lines.append(f"* Paired test `{key}`: {json.dumps(tst[key])}")
        else:
            lines.append("* Sealed test: **not yet evaluated** (split still sealed).")
        ctl = load(cfg["dir"] / "controls.json")
        if ctl:
            lines.append("* Controls (validation): " + json.dumps({k: v for k, v in ctl.items() if k in (
                "n_val", "baseline_val_acc", "final_val_acc", "mcnemar_exact_p_two_sided", "attribution_val_acc",
                "random_conv_features_same_head_val_acc", "random_conv_features_lda_head_val_acc",
                "frac_random_ge_baseline", "frac_random_ge_final", "label_shuffled_head_on_final_extractor_val_acc",
                "frac_shuffle_ge_final", "random_features_loo_acc", "frac_random_loo_ge_final")}))
        if aud:
            lines.append(f"* Audit: passed = **{aud.get('passed')}**; iterations replayed hash-exact: "
                         f"{(aud.get('weight_updates') or aud.get('consistency', {})).get('iterations_replayed', aud.get('consistency', {}).get('iterations_audited'))}")
        lines.append("")
    return "\n".join(lines) + "\n"


def ledger() -> str:
    lines = ["# 05 - Iteration ledger (generated by scripts/build_research_record.py)", "",
             "Every iteration of every experiment, in order. 'params' = number of changed scalar parameters. The full hypothesis, operations and old/new values",
             "are in `data/<experiment>/experiment_history.json` and `parameter_changes.json`.", ""]
    for name, cfg in EXPERIMENTS.items():
        hist = [h for h in load(cfg["dir"] / "experiment_history.json", []) if h.get("id") != "iter000"]
        k = cfg["acc_key"]
        lines += [f"## {name} ({len(hist)} iterations)", "",
                  f"| id | title | params | val acc | {cfg['acc_label']} | decision | reason |", "|---|---|---|---|---|---|---|"]
        for h in hist:
            p, n = h.get("previous_metrics", {}), h.get("new_metrics", {})
            title = h.get("title", "").replace("|", "/")
            lines.append(f"| {h['id']} | {title} | {h.get('n_changed_parameters', '-')} | "
                         f"{p.get('val_acc', 0):.4f}->{n.get('val_acc', 0):.4f} | {p.get(k, 0):.4f}->{n.get(k, 0):.4f} | "
                         f"**{h.get('decision', '').upper()}** | {h.get('decision_reason', '').replace('|', '/')} |")
        lines += ["", "### Hypotheses (as written before each edit)", ""]
        for h in hist:
            lines += [f"* **{h['id']} - {h.get('title', '')}**",
                      f"  * Observed: {h.get('observed', '')}",
                      f"  * Hypothesis: {h.get('hypothesis', '')}",
                      f"  * Parameters: {h.get('selected', '')}",
                      f"  * Expected / risks: {h.get('expected', '')} / {h.get('risks', '')}"]
        lines.append("")
    return "\n".join(lines) + "\n"


def main() -> None:
    OUT.mkdir(parents=True, exist_ok=True)
    snapshot_data()
    (OUT / "04_RESULTS_SUMMARY.md").write_text(summary())
    (OUT / "05_ITERATION_LEDGER.md").write_text(ledger())
    print("wrote", OUT / "04_RESULTS_SUMMARY.md", OUT / "05_ITERATION_LEDGER.md", "and data/ snapshots")


if __name__ == "__main__":
    main()
